// placeOfNPA is an area code's country and region as NANPA names them.
func placeOfNPA(country, loc string) (string, string) {
	switch country {
	case "US":
		if t, ok := usTerritories[loc]; ok {
			return t, ""
		}
		if s, ok := usStates[loc]; ok {
			return "US", s
		}
		return "", ""
	case "CANADA":
		if p, ok := caProvinces[loc]; ok {
			return "CA", p
		}
		return "", ""
	}
	return nanpCountries[country], ""
}
