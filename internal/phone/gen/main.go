// Command gen makes the phone package's tables from a checkout of
// Google's libphonenumber (Apache License 2.0): its territories' calling
// codes, dialing prefixes, number patterns and formats (metadata.go), and
// the places numbers are in, by prefix, in English (places.gz); and,
// from NANPA's report of the North American area codes, which of those
// are in service and where (nanpa.go).
//
//	git clone --depth 1 https://github.com/google/libphonenumber
//	curl -O https://reports.nanpa.com/public/npa_report.csv
//	go run ./internal/phone/gen -src libphonenumber -nanpa npa_report.csv
package main

