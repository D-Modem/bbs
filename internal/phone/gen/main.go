// Command gen makes the phone package's tables from a checkout of
// Google's libphonenumber (Apache License 2.0): its territories' calling
// codes, dialing prefixes, number patterns and formats (metadata.go), and
// the places numbers are in, by prefix, in English (places.gz).
//
//	git clone --depth 1 https://github.com/google/libphonenumber
//	go run ./internal/phone/gen -src libphonenumber
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type desc struct {
	Pattern string `xml:"nationalNumberPattern"`
}

type numberFormat struct {
	Pattern string   `xml:"pattern,attr"`
	Leading []string `xml:"leadingDigits"`
	Format  string   `xml:"format"`
	Intl    *string  `xml:"intlFormat"`
}

type territoryXML struct {
	ID         string         `xml:"id,attr"`
	Code       string         `xml:"countryCode,attr"`
	Main       bool           `xml:"mainCountryForCode,attr"`
	Intl       string         `xml:"internationalPrefix,attr"`
	National   string         `xml:"nationalPrefix,attr"`
	Parsing    string         `xml:"nationalPrefixForParsing,attr"`
	Transform  string         `xml:"nationalPrefixTransformRule,attr"`
	Leading    string         `xml:"leadingDigits,attr"`
	Formats    []numberFormat `xml:"availableFormats>numberFormat"`
	General    desc           `xml:"generalDesc"`
	FixedLine  *desc          `xml:"fixedLine"`
	Mobile     *desc          `xml:"mobile"`
	Pager      *desc          `xml:"pager"`
	TollFree   *desc          `xml:"tollFree"`
	Premium    *desc          `xml:"premiumRate"`
	SharedCost *desc          `xml:"sharedCost"`
	Personal   *desc          `xml:"personalNumber"`
	VoIP       *desc          `xml:"voip"`
	UAN        *desc          `xml:"uan"`
	Voicemail  *desc          `xml:"voicemail"`
}

var space = regexp.MustCompile(`\s+`)

func clean(s string) string { return space.ReplaceAllString(s, "") }

func main() {
	src := flag.String("src", "", "a checkout of github.com/google/libphonenumber")
	out := flag.String("out", "internal/phone", "where the tables go")
	flag.Parse()
	if *src == "" {
		log.Fatal("-src: the libphonenumber checkout")
	}
	commit := "unknown"
	if b, err := exec.Command("git", "-C", *src, "log", "-1", "--format=%H (%cs)").Output(); err == nil {
		commit = strings.TrimSpace(string(b))
	}
	raw, err := os.ReadFile(filepath.Join(*src, "resources", "PhoneNumberMetadata.xml"))
	if err != nil {
		log.Fatal(err)
	}
	var doc struct {
		Territories []territoryXML `xml:"territories>territory"`
	}
	if err := xml.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/phone/gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// From libphonenumber's PhoneNumberMetadata.xml, at %s\n", commit)
	fmt.Fprintf(&b, "// (Copyright The Libphonenumber Authors, Apache License 2.0: LICENSE.libphonenumber).\n\n")
	fmt.Fprintf(&b, "package phone\n\nconst dataVersion = %q\n\nvar territories = []territory{\n", commit)
	for _, t := range doc.Territories {
		for _, re := range []string{t.Intl, t.Parsing, t.Leading, t.General.Pattern} {
			if _, err := regexp.Compile(clean(re)); err != nil {
				log.Fatalf("%s: %v", t.ID, err)
			}
		}
		fmt.Fprintf(&b, "{id: %q, code: %q, main: %v, intl: %q, national: %q, parsing: %q, transform: %q, leading: %q,\ngeneral: %q,\n",
			t.ID, t.Code, t.Main, clean(t.Intl), t.National, clean(t.Parsing), t.Transform, clean(t.Leading), clean(t.General.Pattern))
		b.WriteString("kinds: []kindPattern{")
		for _, k := range []struct {
			kind Kind
			d    *desc
		}{{"fixedLine", t.FixedLine}, {"mobile", t.Mobile}, {"tollFree", t.TollFree}, {"premiumRate", t.Premium},
			{"sharedCost", t.SharedCost}, {"voip", t.VoIP}, {"personalNumber", t.Personal}, {"pager", t.Pager},
			{"uan", t.UAN}, {"voicemail", t.Voicemail}} {
			if k.d == nil || clean(k.d.Pattern) == "" {
				continue
			}
			p := clean(k.d.Pattern)
			if _, err := regexp.Compile(p); err != nil {
				log.Fatalf("%s %s: %v", t.ID, k.kind, err)
			}
			fmt.Fprintf(&b, "{%s, %q},\n", kindConst[k.kind], p)
		}
		b.WriteString("},\n")
		if len(t.Formats) > 0 {
			b.WriteString("formats: []numberFormat{")
			for _, f := range t.Formats {
				lead := ""
				if len(f.Leading) > 0 {
					lead = clean(f.Leading[len(f.Leading)-1])
				}
				intl := strings.TrimSpace(f.Format)
				if f.Intl != nil {
					intl = strings.TrimSpace(*f.Intl)
				}
				fmt.Fprintf(&b, "{%q, %q, %q, %q},\n", clean(f.Pattern), lead, strings.TrimSpace(f.Format), intl)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	code, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*out, "metadata.go"), code, 0o644); err != nil {
		log.Fatal(err)
	}
	places(filepath.Join(*src, "resources", "geocoding", "en"), filepath.Join(*out, "places.gz"), commit)
	lic, err := os.ReadFile(filepath.Join(*src, "LICENSE"))
	if err == nil {
		err = os.WriteFile(filepath.Join(*out, "LICENSE.libphonenumber"), lic, 0o644)
	}
	if err != nil {
		log.Fatal(err)
	}
}

type Kind string

var kindConst = map[Kind]string{"fixedLine": "FixedLine", "mobile": "Mobile", "tollFree": "TollFree",
	"premiumRate": "Premium", "sharedCost": "SharedCost", "voip": "VoIP", "personalNumber": "Personal",
	"pager": "Pager", "uan": "UAN", "voicemail": "Voicemail"}

// places writes the geocoding files as one: the descriptions, one a line;
// an empty line; then the prefixes in order, each as the length it shares
// with the one before, a comma, the rest of its digits, a space and its
// description's line number.
func places(dir, out, commit string) {
	files, err := filepath.Glob(filepath.Join(dir, "*.txt"))
	if err != nil || len(files) == 0 {
		log.Fatalf("%s: no geocoding files", dir)
	}
	type entry struct{ prefix, desc string }
	var es []entry
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		for _, l := range strings.Split(string(b), "\n") {
			l = strings.TrimSpace(l)
			if l == "" || l[0] == '#' {
				continue
			}
			p, d, ok := strings.Cut(l, "|")
			if !ok {
				log.Fatalf("%s: %q", f, l)
			}
			if _, err := strconv.ParseUint(p, 10, 64); err != nil || len(p) > 18 {
				log.Fatalf("%s: prefix %q", f, p)
			}
			es = append(es, entry{p, d})
		}
	}
	sort.Slice(es, func(i, j int) bool { return es[i].prefix < es[j].prefix })
	index := map[string]int{}
	var descs []string
	for _, e := range es {
		if _, ok := index[e.desc]; !ok {
			index[e.desc] = 0
			descs = append(descs, e.desc)
		}
	}
	sort.Strings(descs)
	for i, d := range descs {
		index[d] = i
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# libphonenumber geocoding (en), %s; Apache License 2.0\n", commit)
	for _, d := range descs {
		b.WriteString(d + "\n")
	}
	b.WriteString("\n")
	prev := ""
	for _, e := range es {
		c := 0
		for c < len(prev) && c < len(e.prefix) && prev[c] == e.prefix[c] {
			c++
		}
		fmt.Fprintf(&b, "%d,%s %d\n", c, e.prefix[c:], index[e.desc])
		prev = e.prefix
	}
	var z bytes.Buffer
	w, _ := gzip.NewWriterLevel(&z, gzip.BestCompression)
	w.Write(b.Bytes())
	w.Close()
	if err := os.WriteFile(out, z.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d places, %d descriptions, %d bytes", len(es), len(descs), z.Len())
}
