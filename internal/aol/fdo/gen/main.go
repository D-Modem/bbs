// Command gen makes the fdo package's atom table (atomtable.go) from
// AtomForge's dump of AOL's ADA.BIN, the atom list that ships with the
// FDO91 compiler (Ada32.dll): every atom's protocol, number, name,
// argument type and indent flags.
//
//	git clone --depth 1 https://github.com/iconidentify/atomforge-fdo-java
//	go run ./internal/aol/fdo/gen -src atomforge-fdo-java
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type atomJSON struct {
	Name     string   `json:"name"`
	Protocol int      `json:"protocol"`
	Atom     int      `json:"atom"`
	Type     string   `json:"type"`
	Flags    []string `json:"flags"`
}

// typeNames are the fdo package's names for ADA.BIN's argument types,
// keyed by AtomForge's names for them (some of which are guesses that
// don't fit the atoms that have them: "STREAM_LEGACY" is the named-value
// type of mat_position, "BOOL_LEGACY" a variable letter).
var typeNames = map[string]string{
	"RAW": "TypeRaw", "DWORD": "TypeDword", "STRING": "TypeString",
	"BOOL": "TypeBool", "GID": "TypeGID", "STREAM": "TypeStream",
	"OBJSTART": "TypeObject", "ORIENT": "TypeOrient", "TOKEN": "TypeToken",
	"TOKENARG": "TypeCriterion", "ALERT": "TypeAlert", "ATOM": "TypeAtom",
	"COLORDATA": "TypeByteList", "IGNORE": "TypeIgnore",
	"VARLOOKUP": "TypeVarNumber", "CRITERION": "TypeVarString",
	"BOOL_LEGACY": "TypeVar", "CRITERION_LEGACY": "TypeList",
	"STREAM_LEGACY": "TypeEnum", "VAR": "TypeType14",
	"VARDWORD": "TypeType15",
}

var flagNames = map[string]string{"INDENT": "FlagIndent", "OUTDENT": "FlagOutdent", "EOS": "FlagEOS"}

func main() {
	src := flag.String("src", "atomforge-fdo-java", "a checkout of atomforge-fdo-java")
	out := flag.String("out", "internal/aol/fdo/atomtable.go", "the file to write")
	flag.Parse()

	raw, err := os.ReadFile(filepath.Join(*src, "src/test/resources/ada-bin-baseline.json"))
	if err != nil {
		log.Fatal(err)
	}
	var doc struct {
		Generated string     `json:"generated"`
		Atoms     []atomJSON `json:"atoms"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}
	sort.Slice(doc.Atoms, func(i, j int) bool {
		a, b := doc.Atoms[i], doc.Atoms[j]
		if a.Protocol != b.Protocol {
			return a.Protocol < b.Protocol
		}
		return a.Atom < b.Atom
	})
	rev := "unknown"
	if b, err := exec.Command("git", "-C", *src, "rev-parse", "HEAD").Output(); err == nil {
		rev = strings.TrimSpace(string(b))
	}

	var w bytes.Buffer
	fmt.Fprintf(&w, "// Code generated by go run ./internal/aol/fdo/gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&w, "// From AtomForge's dump of ADA.BIN (src/test/resources/ada-bin-baseline.json,\n")
	fmt.Fprintf(&w, "// generated %s), atomforge-fdo-java at %s\n", doc.Generated, rev)
	fmt.Fprintf(&w, "// (Copyright AtomForge Contributors, MIT License: LICENSE.atomforge).\n\n")
	fmt.Fprintf(&w, "package fdo\n\n")
	fmt.Fprintf(&w, "var atomTable = [...]Atom{\n")
	for _, a := range doc.Atoms {
		t, ok := typeNames[a.Type]
		if !ok {
			log.Fatalf("%s: unknown type %s", a.Name, a.Type)
		}
		var fl []string
		for _, f := range a.Flags {
			fl = append(fl, flagNames[f])
		}
		flags := "0"
		if len(fl) > 0 {
			flags = strings.Join(fl, "|")
		}
		fmt.Fprintf(&w, "\t{%d, %d, %q, %s, %s},\n", a.Protocol, a.Atom, strings.ToLower(a.Name), t, flags)
	}
	fmt.Fprintf(&w, "}\n")
	b, err := format.Source(w.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, b, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d atoms", len(doc.Atoms))
}
